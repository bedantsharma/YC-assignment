"""Compare damage detectors on the staged damage room's photos, image by image.

Reads outputs/damage_cmp/<model>/detections.json (from
`FLOORPLAN_GEMINI_MODEL=<model> uv run floorplan damage data/home_c/photos/room1
--crack-pass --out outputs/damage_cmp/<model>`; replays offline from data/damage_cache with
FLOORPLAN_DAMAGE_CACHE_ONLY=1) and the eye labels in data/gt/home_c_damage_labels.json.
Image-level scoring: a class counts as found in a photo if the model reports it anywhere
in that photo. Writes docs/damage_models.md.

    uv run scripts/damage_compare.py [model ...]
"""

import json
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LABELS = ROOT / "data/gt/home_c_damage_labels.json"
RUNS = ROOT / "outputs/damage_cmp"
OUT = ROOT / "docs/damage_models.md"
MODELS = ["gemini-3.1-pro-preview", "gemini-3.8-flash", "gemini-3.6-flash"]


def main(models: list[str]) -> None:
    labels = json.loads(LABELS.read_text())
    present = {c: set(v) for c, v in labels["present"].items()}
    scored = labels["classes_scored"]
    rows, per_image, extra = [], {}, {}
    for model in models:
        rec = json.loads((RUNS / model / "detections.json").read_text())
        images = [Path(p).stem for p in rec["images"]]
        found: dict[str, set[str]] = {}
        for d in rec["detections"]:
            found.setdefault(d["label"], set()).add(Path(d["image"]).stem)
        per_image[model] = found
        extra[model] = Counter(
            (d["label"], d["source"]) for d in rec["detections"] if d["label"] not in scored
        )
        log = (RUNS / f"{model}.log").read_text() if (RUNS / f"{model}.log").exists() else ""
        secs = re.search(r"seconds (\d+)", log)
        for c in scored:
            tp = len(found.get(c, set()) & present[c])
            fp = len(found.get(c, set()) - present[c])
            fn = len(present[c] - found.get(c, set()))
            rows.append((model, c, tp, fp, fn))
        clean = set(labels["no_damage"]) & set(images)
        damage_classes = {"crack", "water_stain", "mould", "hole", "peeling_paint"}
        noisy = {
            Path(d["image"]).stem
            for d in rec["detections"]
            if d["label"] in damage_classes and Path(d["image"]).stem in clean
        }
        rows.append((model, "_clean", len(clean) - len(noisy), len(noisy), 0))
        rows.append((model, "_time", int(secs.group(1)) if secs else None, len(images), 0))

    lines = [
        "# Damage detectors on the staged room's photos",
        "",
        "Generated by `uv run scripts/damage_compare.py` from the cached Gemini answers",
        "(`data/damage_cache/`). 26 photos of the staged bedroom (`data/home_c/photos/room1`),",
        "main prompt + crack pass. Reference: **eye labels** (`data/gt/home_c_damage_labels.json`,",
        "labelled by Claude from the photos, image-level presence only, not yet checked by a",
        "person), so this measures which photos each class is found in, not box accuracy.",
        "",
        "| Model | Class | Found (TP) | False alarms (FP) | Missed (FN) | Recall | Precision |",
        "|---|---|---|---|---|---|---|",
    ]
    for model, c, tp, fp, fn in rows:
        if c.startswith("_"):
            continue
        rec_ = f"{tp / (tp + fn):.2f}" if tp + fn else "-"
        prec = f"{tp / (tp + fp):.2f}" if tp + fp else "-"
        lines.append(f"| {model} | {c} | {tp} | {fp} | {fn} | {rec_} | {prec} |")
    lines += [
        "",
        "| Model | Damage-free photos with no damage reported | Wall-clock (26 photos, 2 calls each, 3 models in parallel) |",
        "|---|---|---|",
    ]
    for model in models:
        clean = next(r for r in rows if r[0] == model and r[1] == "_clean")
        t = next(r for r in rows if r[0] == model and r[1] == "_time")
        secs = f"{t[2]} s ({t[2] / t[3]:.0f} s per photo)" if t[2] else "-"
        lines.append(f"| {model} | {clean[2]} of {clean[2] + clean[3]} | {secs} |")
    lines += ["", "Unscored detections (crack, peeling paint, mould, sockets), by prompt:", ""]
    for model in models:
        items = ", ".join(f"{lab} ({src}) {n}" for (lab, src), n in sorted(extra[model].items()))
        lines.append(f"- {model}: {items or 'none'}")
    lines += ["", "Per photo (classes reported):", ""]
    lines.append("| Photo | Eye label | " + " | ".join(models) + " |")
    lines.append("|---|---|" + "---|" * len(models))
    all_images = sorted(set(labels["no_damage"]) | {i for v in present.values() for i in v})
    for img in all_images:
        truth = ", ".join(c for c in scored if img in present[c]) or "-"
        cells = []
        for model in models:
            got = sorted(c for c, imgs in per_image[model].items() if img in imgs)
            cells.append(", ".join(got) or "-")
        lines.append(f"| {img} | {truth} | " + " | ".join(cells) + " |")
    OUT.write_text("\n".join(lines) + "\n")
    print("\n".join(lines[8 : 9 + len(rows)]))
    print(f"-> {OUT}")


if __name__ == "__main__":
    main(sys.argv[1:] or MODELS)
